-- Super+Shift+Q: transparent kitty floating over the current screen (e.g. over fullscreen Chrome)
hl.window_rule({
    name   = "float-terminal",
    match  = { class = "floatingterm" },
    float  = true,
    center = true,
    size   = "1440 1080",
})

-- Cheatsheet window (hypr-cheatsheet script)
hl.window_rule({
    name   = "float-cheatsheet",
    match  = { class = "kitty", title = "cheatsheet" },
    float  = true,
    center = true,
    size   = "1200 800",
})

local suppressMaximizeRule = hl.window_rule({
    -- Ignore maximize requests from all apps. You'll probably like this.
    name  = "suppress-maximize-events",
    match = { class = ".*" },

    suppress_event = "maximize",
})
-- suppressMaximizeRule:set_enabled(false)

hl.window_rule({
    -- Fix some dragging issues with XWayland
    name  = "fix-xwayland-drags",
    match = {
        class      = "^$",
        title      = "^$",
        xwayland   = true,
        float      = true,
        fullscreen = false,
        pin        = false,
    },

    no_focus = true,
})

